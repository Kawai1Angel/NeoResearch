import path from "path"
import { fileURLToPath } from "url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const dir = path.resolve(__dirname, "..")

process.chdir(dir)

const modelsUrl = process.env.NEORESEARCH_MODELS_URL || "https://models.dev"
const snapshotPath = path.join(dir, "src/provider/models-snapshot.js")

async function readExistingModelsSnapshot() {
  const existing = await Bun.file(snapshotPath).text()
  const marker = "export const snapshot = "
  const start = existing.indexOf(marker)
  if (start === -1) {
    throw new Error(`Existing models snapshot is missing ${JSON.stringify(marker)}`)
  }
  return existing
    .slice(start + marker.length)
    .trim()
    .replace(/;\s*$/, "")
}

async function loadModelsData() {
  if (process.env.MODELS_DEV_API_JSON) {
    return await Bun.file(process.env.MODELS_DEV_API_JSON).text()
  }

  try {
    const response = await fetch(`${modelsUrl}/api.json`)
    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText}`)
    }
    return await response.text()
  } catch (e) {
    console.warn(`Using existing models-snapshot.js because ${modelsUrl}/api.json could not be fetched: ${e}`)
    return await readExistingModelsSnapshot()
  }
}

// Fetch and generate models.dev snapshot. Release checks can run offline by falling back to the checked-in snapshot.
const modelsData = await loadModelsData()
await Bun.write(
  snapshotPath,
  `// @ts-nocheck\n// Auto-generated by build.ts - do not edit\nexport const snapshot = ${modelsData}\n`,
)
await Bun.write(
  path.join(dir, "src/provider/models-snapshot.d.ts"),
  `// Auto-generated by build.ts - do not edit\nexport declare const snapshot: Record<string, unknown>\n`,
)
console.log("Generated models-snapshot.js")
