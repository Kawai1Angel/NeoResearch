"use strict";

const fs = require("fs");
const path = require("path");
const { describeCandidateFamily, describeCandidateId } = require("./candidate-utils");

function modelDesignPaths(projectRoot = process.cwd()) {
  const stateDir = path.join(projectRoot, ".neo-cast");
  return {
    stateDir,
    jsonlPath: path.join(stateDir, "model_designs.jsonl"),
    markdownPath: path.join(stateDir, "model_designs.md"),
  };
}

function architectureDetails(candidate) {
  if (candidate.schema_version === "model_recipe.v1") {
    return {
      input: candidate.input || null,
      architecture: candidate.architecture || null,
      constraints: candidate.constraints || null,
    };
  }
  if (candidate.recipe_version === "recipe_schema_v1") {
    return {
      preprocessing: candidate.preprocessing || null,
      embedding: candidate.embedding || null,
      backbone: candidate.backbone || null,
      fusion: candidate.fusion || null,
      prediction_head: candidate.prediction_head || null,
      post_processing: candidate.post_processing || null,
      constraints: candidate.constraints || null,
    };
  }
  return {
    model_family: candidate.model_family || null,
    architecture: candidate.architecture || null,
    constraints: candidate.constraints || null,
  };
}

function trainingDetails(candidate) {
  if (candidate.training) return candidate.training;
  if (candidate.training_strategy) return candidate.training_strategy;
  if (candidate.train_config) return candidate.train_config;
  return null;
}

function buildModelDesignRecord(candidate, options = {}) {
  return {
    schema_version: "model_design_log_entry.v1",
    recorded_at: options.recordedAt || new Date().toISOString(),
    attempt: options.attempt || null,
    source: options.source || null,
    candidate_id: describeCandidateId(candidate),
    model_name: candidate.model_name || null,
    model_family: describeCandidateFamily(candidate),
    hypothesis: candidate.hypothesis || null,
    recipe_version_id: options.recipeVersionId || null,
    candidate_path: options.candidatePath || null,
    architecture: architectureDetails(candidate),
    training: trainingDetails(candidate),
  };
}

function readJsonlRecords(jsonlPath) {
  if (!fs.existsSync(jsonlPath)) return [];
  return fs.readFileSync(jsonlPath, "utf8")
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => JSON.parse(line));
}

function fencedJson(value) {
  return `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
}

function renderMarkdown(records) {
  const lines = [
    "# Model Design Log",
    "",
    "This file is generated by `neo-cast design` and records candidates in append order.",
    "",
  ];
  records.forEach((record, index) => {
    lines.push(
      `## ${index + 1}. ${record.candidate_id}`,
      "",
      `- attempt: ${record.attempt ?? "NA"}`,
      `- source: ${record.source ?? "NA"}`,
      `- model_family: ${record.model_family ?? "NA"}`,
      `- model_name: ${record.model_name ?? "NA"}`,
      `- recipe_version_id: ${record.recipe_version_id ?? "NA"}`,
      `- candidate_path: ${record.candidate_path ?? "NA"}`,
      `- hypothesis: ${record.hypothesis ?? "NA"}`,
      "",
      "### Architecture",
      "",
      fencedJson(record.architecture),
      "",
      "### Training",
      "",
      fencedJson(record.training),
      "",
    );
  });
  return `${lines.join("\n")}\n`;
}

function appendModelDesignRecord(projectRoot, candidate, options = {}) {
  const paths = modelDesignPaths(projectRoot);
  fs.mkdirSync(paths.stateDir, { recursive: true });
  const record = buildModelDesignRecord(candidate, options);
  fs.appendFileSync(paths.jsonlPath, `${JSON.stringify(record)}\n`, "utf8");
  const records = readJsonlRecords(paths.jsonlPath);
  fs.writeFileSync(paths.markdownPath, renderMarkdown(records), "utf8");
  return { ...paths, record };
}

module.exports = {
  appendModelDesignRecord,
  buildModelDesignRecord,
  modelDesignPaths,
  renderMarkdown,
};
